"""T_MASK study on the CDnet thermal sequences (why lakeSide scores F1 0.22 with the default T_MASK = 400 counts).

The background model and the NUC output do not depend on T_MASK; only `raw_mask = |y - B| > T_MASK` and the morphology after it
do. So each sequence is run through the bit-accurate pipeline ONCE (noisy typical sensor + NUC + bad-pixel repair, the realistic
condition), the per-frame |y - B| is kept, and every threshold is applied afterwards with the same 3x3 open + close as the RTL
(model/pipeline_int.py: detector_frame, morph_open_close). T_MASK is a run-time CSR (0x06), so the best value per scene can be set
from the viewer / HPS without a rebuild.

  python scripts/study_tmask.py                          # 5 sequences, writes docs/results/tmask_sweep.md
  python scripts/study_tmask.py --seq lakeSide --scored 200
1 grey level of the 8-bit CDnet input = 16 counts."""
import argparse
import os
import sys
import time

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.dirname(__file__))
from model import datasets as D, metrics as M, noise_model as nm, pipeline_int as P  # noqa: E402
from eval_cdnet import CDNET, OUT, first_scored  # noqa: E402

THRESHOLDS = (32, 48, 64, 96, 128, 160, 200, 256, 320, 400, 512, 640)


def diffs_of(c, ys):
    """|y - B| per frame (counts << BF), exactly as P.detector_frame computes it (B starts at the first frame)."""
    s = P.State.init(c)
    out = []
    for y14 in ys:
        yb = y14.astype(np.int64) << c.BF
        if s.n == 0:
            diff = np.zeros_like(yb)
            newB = yb
        else:
            diff = np.abs(yb - s.B)
            sh = min(c.KB, int(np.ceil(np.log2(s.n + 1))))
            newB = s.B + P.rshift_round(yb - s.B, sh)
        s.B = newB
        s.n = min(s.n + 1, 255)
        out.append(diff)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seq", nargs="*", default=list(D.CDNET_THERMAL))
    ap.add_argument("--preset", default="typical")
    ap.add_argument("--scored", type=int, default=300)
    ap.add_argument("--warm", type=int, default=150)
    ap.add_argument("--seed", type=int, default=1)
    a = ap.parse_args()
    c = P.Cfg()
    assert a.warm > c.DET_WARM
    results = {}
    for seq in a.seq:
        t0 = first_scored(seq)
        start = max(0, t0 - 1 - a.warm)
        scene, gt, valid, fe = D.load_cdnet(CDNET, seq, max_frames=(t0 - 1 - start) + a.scored, start=start)
        fe = max(fe, c.DET_WARM + 1)
        raw, _ = nm.add_noise(scene, a.preset, seed=a.seed)
        tic = time.time()
        s = P.State.init(c)
        ys = [P.frame_step(c, s, f).y14 for f in raw]
        diffs = diffs_of(c, ys)
        res = {}
        for T in THRESHOLDS:
            masks = np.stack([P.morph_open_close(d > (T << c.BF)) for d in diffs[fe:]])
            res[T] = M.prf(masks, gt[fe:], valid[fe:])
        results[seq] = res
        best = max(THRESHOLDS, key=lambda T: res[T]["f1"])
        print("%-10s scored %d frames in %.0f s: default T=400 F1 %.3f, best T=%d F1 %.3f" %
              (seq, len(ys) - fe, time.time() - tic, res[400]["f1"], best, res[best]["f1"]), flush=True)

    L = ["# T_MASK sweep on the CDnet thermal sequences", "",
         "Generated by `scripts/study_tmask.py` (args: `%s`)." % " ".join(sys.argv[1:]), "",
         "Realistic condition: `%s` sensor non-uniformity, full pipeline (NUC + bad-pixel repair), bit-accurate model. The background "
         "and the NUC output do not depend on T_MASK, so one pipeline pass per sequence is thresholded at every value (same 3x3 open + close "
         "as the RTL). %d warm-up frames, %d scored frames, CDnet scoring rules (spatial and temporal ROI, 'unknown' excluded). "
         "1 grey level of the 8-bit input = 16 counts. T_MASK is a run-time CSR (word 0x06)." % (a.preset, a.warm, a.scored), "",
         "F1 by threshold (counts):", "",
         "| sequence | " + " | ".join(str(T) for T in THRESHOLDS) + " | best T | best F1 | F1 at 400 |",
         "|---|" + "---|" * (len(THRESHOLDS) + 3)]
    for seq, res in results.items():
        best = max(THRESHOLDS, key=lambda T: res[T]["f1"])
        L.append("| %s | " % seq + " | ".join("%.3f" % res[T]["f1"] for T in THRESHOLDS) +
                 " | %d | %.3f | %.3f |" % (best, res[best]["f1"], res[400]["f1"]))
    L += ["", "Precision / recall / false-alarm rate at the best threshold and at 400:", "",
          "| sequence | T | precision | recall | false-alarm rate | F1 |", "|---|---|---|---|---|---|"]
    for seq, res in results.items():
        best = max(THRESHOLDS, key=lambda T: res[T]["f1"])
        for T in sorted({best, 400}):
            r = res[T]
            L.append("| %s | %d | %.3f | %.3f | %.5f | %.3f |" % (seq, T, r["precision"], r["recall"], r["far"], r["f1"]))
    mean = {T: float(np.mean([res[T]["f1"] for res in results.values()])) for T in THRESHOLDS}
    bt = max(THRESHOLDS, key=lambda T: mean[T])
    L += ["", "Mean F1 over the sequences: " + ", ".join("%d: %.3f" % (T, mean[T]) for T in THRESHOLDS) +
          ". Best single value for all of them: **T_MASK = %d** (mean F1 %.3f; 400 gives %.3f)." % (bt, mean[bt], mean[400]), ""]
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "tmask_sweep.md"), "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote docs/results/tmask_sweep.md; best single T_MASK for all: %d (mean F1 %.3f, 400: %.3f)" % (bt, mean[bt], mean[400]))


if __name__ == "__main__":
    main()
