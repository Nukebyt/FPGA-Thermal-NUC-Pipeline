"""Write a resources / timing page from the Quartus reports of a project (fit summary, STA summary, RAM summary).
Run after scripts/build_quartus.sh. Records the source state so a number can always be traced to a build.

  python scripts/make_resources.py                                           # quartus/thermal -> docs/results/resources.md
  python scripts/make_resources.py --project quartus/thermal_soc --rev thermal_soc --out docs/results/resources_soc.md
  python scripts/make_resources.py --fingerprint 34dc1643264fbefc            # reports of an older build: its recorded fingerprint"""
import argparse
import datetime
import hashlib
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
OUT = None


def read(name):
    with open(os.path.join(OUT, name), errors="replace") as f:
        return f.read()


def main():
    global OUT
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", default="quartus/thermal")
    ap.add_argument("--rev", default="thermal")
    ap.add_argument("--out", default="docs/results/resources.md")
    ap.add_argument("--fingerprint", default=None, help="use this fingerprint instead of hashing rtl/ (reports of an older build)")
    a = ap.parse_args()
    OUT = os.path.join(ROOT, a.project, "output_files")
    fit = read(a.rev + ".fit.summary")
    sta = read(a.rev + ".sta.summary")
    rpt = read(a.rev + ".fit.rpt")
    lines = ["# Resources and timing (%s)" % a.project, "",
             "Generated by `scripts/make_resources.py` on %s from `%s/output_files`." % (datetime.date.today(), a.project), ""]
    # RTL fingerprint: hash of every RTL file, so the numbers can be tied to a source state
    h = hashlib.sha256()
    for fn in sorted(os.listdir(os.path.join(ROOT, "rtl"))):
        with open(os.path.join(ROOT, "rtl", fn), "rb") as f:
            h.update(fn.encode() + f.read())
    lines += ["RTL fingerprint (sha256 of rtl/*): `%s`" % (a.fingerprint or h.hexdigest()[:16]), "", "## Fitter summary", "", "```"]
    lines += [l for l in fit.splitlines() if re.match(r"\s*(Logic utilization|Total (registers|pins|block memory|RAM Blocks|DSP|PLLs))", l)]
    lines += ["```", "", "## Timing (worst corner first)", "", "```"]
    ent = re.findall(r"Type\s*:\s*(.+?)\s*'(.+?)'\s*\nSlack\s*:\s*(-?[\d.]+)\s*\nTNS\s*:\s*(-?[\d.]+)", sta)
    for typ, clk, slack, tns in sorted(ent, key=lambda e: float(e[2])):
        lines.append("%-34s %-70s slack %8s  TNS %s" % (typ, clk[-70:], slack, tns))
    lines += ["```", ""]
    m = re.search(r"; Fitter RAM Summary.*?\n(.*?)\n\n", rpt, re.S)
    if m:
        lines += ["## RAM summary (from the fit report)", "", "```", m.group(1)[:6000], "```", ""]
    os.makedirs(os.path.dirname(os.path.join(ROOT, a.out)), exist_ok=True)
    with open(os.path.join(ROOT, a.out), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines[:40]))


if __name__ == "__main__":
    sys.exit(main())
